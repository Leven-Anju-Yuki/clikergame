import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
let picked;
let directoryCalls=0;
const folder={name:'Lapinous_Sauvegardes'};
const context={window:{showDirectoryPicker:async()=>{directoryCalls++;return folder;},showOpenFilePicker:async options=>{picked=options;return [{getFile:async()=>({text:async()=>'{"name":"Azur"}'})}];}},document:{addEventListener(){}},indexedDB:{open(){throw Error('unavailable');}},Blob,URL,setTimeout,Map,Set,Date};
vm.runInNewContext(fs.readFileSync('assets/js/local-files.js','utf8'),context);
const api=context.window.LapinousLocalFiles;
assert.equal((await api.openSaveFile()).name,'Azur');
assert.equal(picked.startIn,'downloads');
assert.equal(directoryCalls,0,'Import never opens a directory picker');
await api.chooseSaves();
assert.equal(directoryCalls,1);
await api.openSaveFile();
assert.equal(picked.startIn,folder,'Reuse the actual remembered folder handle');
assert.equal(directoryCalls,1,'Import does not reconnect the directory');
context.window.showOpenFilePicker=async()=>{const error=Error('cancel');error.name='AbortError';throw error;};
await assert.rejects(api.openSaveFile(),{name:'AbortError'});
console.log('Import : sélecteur direct, dossier mémorisé, Téléchargements par défaut et annulation OK.');
